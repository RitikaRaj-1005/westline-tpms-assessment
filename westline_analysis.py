print(st.groupby('depot')[['raw_30d', 'adj_30d']].describe(percentiles=[.25, .5, .75]).round(1).T.to_string())
print('\n    Stable intervals, median by truck:')
print(st.groupby(['depot', 'truck'])[['raw_30d', 'adj_30d']].median().round(1).to_string())

