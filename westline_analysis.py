# Rules, stated explicitly:
#  * Each twin pair gets a complete 10-minute timeline from its first to last reading (no bins dropped).
#  * A bin's value is the median inner-minus-outer difference over timestamps where BOTH tyres reported.
#    A bin with no paired reading is "no data".
#  * A bin "qualifies" when the difference is beyond the threshold in a given direction:
#      inner deficit: inner - outer < -threshold     outer deficit: inner - outer > +threshold
#  * An episode is a run of at least 2 consecutive qualifying bins (20 minutes).
#    A single "no data" bin inside a run does not break it; two or more "no data" bins in a row, or any
#    bin with data that does not qualify, end the run. The next qualifying run is a new episode.
#  * Reported: qualifying bins (flagged 10-min periods) and episodes, separately, by direction.
#  * These are historical alarm episodes, not confirmed false alarms.
pairs = [(f'{ax}{s}I', f'{ax}{s}O') for ax in (4, 5) for s in ('L', 'R')]

def episodes(q, nodata, min_bins=2):
    """q, nodata: boolean Series on a complete 10-min index. Returns list of (start, end, n_qualifying_bins)."""
    out, run, gap, start, last = [], 0, 0, None, None
    for t, qi, nd in zip(q.index, q.values, nodata.values):
        if qi:
            if run == 0: start = t
            run += 1; gap = 0; last = t
        elif nd and run > 0 and gap == 0:
            gap = 1                                   # tolerate one missing bin
        else:
            if run >= min_bins: out.append((start, last, run))
            run, gap = 0, 0
    if run >= min_bins: out.append((start, last, run))
    return out

