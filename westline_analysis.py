# Section 3C — V6 revised: reporting mode vs movement, valid speeds only, GPS-time denominator
# Speed = distance between consecutive GPS fixes / time between those GPS fixes (not receiver times).
# Records without a fix on either side have no speed and are reported separately, not counted as stationary.
d = df[['truck', 'Time', 'GPS Time', 'Latitude', 'Longitude']].sort_values(['truck', 'Time']).reset_index(drop=True).copy()
d['gap'] = d.groupby('truck')['Time'].diff().dt.total_seconds()                  # receiver interval -> defines the mode
d['gps_dt'] = d.groupby('truck')['GPS Time'].diff().dt.total_seconds()           # GPS interval -> used for speed
lat1, lon1 = np.radians(d['Latitude']), np.radians(d['Longitude'])
lat0, lon0 = lat1.groupby(d['truck']).shift(), lon1.groupby(d['truck']).shift()
a = np.sin((lat1 - lat0) / 2) ** 2 + np.cos(lat0) * np.cos(lat1) * np.sin((lon1 - lon0) / 2) ** 2
d['km'] = 6371 * 2 * np.arcsin(np.sqrt(a))
d['kmh'] = d['km'] / (d['gps_dt'] / 3600)
d['mode'] = np.select([d.gap.between(10, 30), d.gap.between(100, 140)], ['fast ~20 s', 'slow ~2 min'], 'other')

for mode in ['fast ~20 s', 'slow ~2 min']:
    sub = d[d['mode'] == mode]
    valid = sub['kmh'].notna()
    v = sub.loc[valid, 'kmh']
    print(f'\n{mode}')
    print(f'  Intervals: {len(sub):,} | with a valid GPS speed: {valid.sum():,} | without (no fix on one side): {(~valid).sum():,}')
    print(f'  Speed (km/h): median {v.median():.1f}, 95th pct {v.quantile(.95):.1f}, max {v.max():.1f}')
    print(f'  Below 3 km/h: {(v < 3).mean()*100:.1f}%  |  3 km/h or more: {(v >= 3).mean()*100:.2f}%  ({(v >= 3).sum():,} intervals)')

