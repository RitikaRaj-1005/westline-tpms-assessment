# Section 3 — Remove duplicates, reshape to one row per tyre reading, sanity checks
import numpy as np

# 3a. Drop the June/July overlap duplicates (F1)
data_cols = [c for c in raw.columns if c not in ('source_file', 'Vehicle')]
df = (raw.drop_duplicates(subset=data_cols, keep='first')
         .drop(columns=extra + ['Vehicle'])          # drop axle 6/7 columns and the unreliable Vehicle field (F2)
         .sort_values(['truck', 'Time'])
         .reset_index(drop=True))
print(f'Rows before: {len(raw):,}  after removing duplicates: {len(df):,}  removed: {len(raw)-len(df):,}')

# 3b. Reshape: one row per truck, time and tyre position
parts = []
for s in SLOTS:
    p = df[['truck', 'Time', 'GPS Time', 'Latitude', 'Longitude', f'{s} PSI', f'{s} TEMP', f'{s} BATT']].copy()
    p.columns = ['truck', 'Time', 'GPS_Time', 'Lat', 'Lon', 'PSI', 'TEMP', 'BATT']
    p['pos'] = s
    parts.append(p)
tyre = pd.concat(parts, ignore_index=True)
tyre['axle'] = tyre['pos'].str[0].astype(int)
tyre['spec'] = tyre['axle'].map({1: 115, 2: 105, 3: 105, 4: 100, 5: 100})
print(f'Tyre-level rows: {len(tyre):,} (= {len(df):,} records x 14 positions)')

# 3c. How often is each sensor missing from a record?
miss = tyre.groupby(['truck', 'pos'])['PSI'].apply(lambda x: x.isna().mean() * 100).unstack().round(1)
print('\n% of records with no packet from that sensor:')
print(miss.to_string())

# 3d. Physically impossible or suspicious values
r = tyre.dropna(subset=['PSI'])
checks = {
    'PSI <= 0':            (r.PSI <= 0).sum(),
    'PSI > 160':           (r.PSI > 160).sum(),
    'TEMP < 0 C':          (r.TEMP < 0).sum(),
    'TEMP > 100 C':        (r.TEMP > 100).sum(),
    'BATT < 0 or > 100':   ((r.BATT < 0) | (r.BATT > 100)).sum(),
    'PSI present, TEMP missing': (r.TEMP.isna()).sum(),
}
print('\nImpossible / suspicious values:')
for k, v in checks.items(): print(f'  {k:28s} {v:,}')

# 3e. Range of readings by axle (all readings, hot and cold mixed)
print('\nPSI and TEMP by axle (all readings):')
print(r.groupby('axle').agg(spec=('spec', 'first'),
                            psi_min=('PSI', 'min'), psi_median=('PSI', 'median'), psi_max=('PSI', 'max'),
                            temp_min=('TEMP', 'min'), temp_median=('TEMP', 'median'), temp_max=('TEMP', 'max')).round(1).to_string())

# 3f. Silent sensors: longest stretch with no packet from a tyre while the receiver kept reporting
def longest_silence(g):
    t = g.loc[g.PSI.notna(), 'Time']
    return t.diff().max().total_seconds() / 3600 if len(t) > 1 else np.nan
sil = tyre.groupby(['truck', 'pos']).apply(longest_silence).round(1)
print('\nLongest silence per tyre (hours) — top 10:')
print(sil.sort_values(ascending=False).head(10).to_string())

# 3g. Any tyre that ever read below 70 PSI (30% under the drive-axle spec) — when, and for how long
low = r[r.PSI < 70].groupby(['truck', 'pos']).agg(first=('Time', 'min'), last=('Time', 'max'),
                                                  readings=('PSI', 'size'), lowest_psi=('PSI', 'min'))
print('\nTyres that ever read below 70 PSI:')
print(low.to_string())

# 3h. Save the clean tables to Drive so later notebooks load in seconds
df.to_parquet(DATA + 'clean_wide.parquet')
tyre.to_parquet(DATA + 'clean_tyre.parquet')
print('\nSaved clean_wide.parquet and clean_tyre.parquet to', DATA)

