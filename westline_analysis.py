# V6. Does the reporting rate follow movement? (tests H4)
#     Distance between consecutive GPS fixes / time -> speed. Compare the ~20 s and ~120 s intervals.
d = df[['truck', 'Time', 'Latitude', 'Longitude']].copy()
d['gap'] = d.groupby('truck')['Time'].diff().dt.total_seconds()
lat1, lon1 = np.radians(d['Latitude']), np.radians(d['Longitude'])
lat0, lon0 = lat1.groupby(d['truck']).shift(), lon1.groupby(d['truck']).shift()
a = np.sin((lat1 - lat0) / 2) ** 2 + np.cos(lat0) * np.cos(lat1) * np.sin((lon1 - lon0) / 2) ** 2
d['km'] = 6371 * 2 * np.arcsin(np.sqrt(a))
d['kmh'] = d['km'] / (d['gap'] / 3600)
d['mode'] = np.select([d.gap.between(10, 30), d.gap.between(100, 140)], ['fast ~20 s', 'slow ~2 min'], 'other')
print('\nV6. Speed between consecutive fixes by reporting mode (km/h):')
print(d[d['mode'] != 'other'].groupby('mode')['kmh'].describe(percentiles=[.05, .5, .95]).round(1).to_string())
print('    Share of fast-mode rows with speed under 3 km/h:',
      round((d.loc[d['mode'] == 'fast ~20 s', 'kmh'] < 3).mean() * 100, 1), '%')
print('    Share of slow-mode rows with speed over 3 km/h:',
      round((d.loc[d['mode'] == 'slow ~2 min', 'kmh'] > 3).mean() * 100, 1), '%')

